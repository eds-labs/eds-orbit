import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = readFileSync(`${root}/docker-compose.yml`, "utf8");
const hash = createHash("sha256").update(source).digest("hex");
function replaceOnce(input, before, after) {
  if (input.split(before).length !== 2)
    throw new Error(
      "Canonical Compose changed; review the PVE adapter before regeneration",
    );
  return input.replace(before, after);
}
const hosts = [
  "orbit.eds-labs.io",
  "n8n.eds-labs.io",
  "analytics.eds-labs.io",
  "analytics.uliquid.vip",
  "postiz.eds-labs.io",
];
let generated = replaceOnce(
  source,
  "  pids_limit: 256\n",
  "  pids_limit: 256\n  extra_hosts:\n" +
    hosts.map((host) => `    - "${host}:10.50.0.12"\n`).join(""),
);
for (const [volume, path, target] of [
  ["orbit_pg", "pg", "/var/lib/postgresql/data"],
  ["orbit_redis", "redis", "/data"],
]) {
  generated = replaceOnce(
    generated,
    `      - ${volume}:${target}\n`,
    `      - type: bind\n        source: /data/orbit-production/${path}\n        target: ${target}\n        bind:\n          create_host_path: false\n`,
  );
}
generated =
  `# Generated by node scripts/render-pve-compose.mjs. Do not edit directly.\n# Canonical docker-compose.yml SHA256: ${hash}\n# VM102 only. Existing data paths must exist; no credentials are stored here.\n` +
  generated;
const path = `${root}/docker-compose.pve.yml`;
const sourceHashPath = `${root}/docker-compose.pve.source.sha256`;
if (process.argv.includes("--check")) {
  if (
    readFileSync(path, "utf8") !== generated ||
    readFileSync(sourceHashPath, "utf8") !== `${hash}\n`
  )
    throw new Error(
      "PVE Compose is stale; review and run node scripts/render-pve-compose.mjs",
    );
  console.log("PVE Compose matches its canonical source");
} else {
  writeFileSync(path, generated);
  // Coolify rewrites the selected YAML before the custom build; keep metadata separate.
  writeFileSync(sourceHashPath, `${hash}\n`);
  console.log("Generated VM102 Compose adapter");
}
