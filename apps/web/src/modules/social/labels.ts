export const socialText = (locale: "en" | "de"): SocialText => (locale === "de" ? de : en);

/** The text for a social error code; unknown codes get the generic text. */
export const accountMessage = (code: string, locale: "en" | "de") => {
  const t = socialText(locale);
  return t.errors[code] ?? t.genericError;
};

/** The text for a media error code; unknown codes get the generic text. */
export const mediaMessage = (code: string, locale: "en" | "de") => {
  const t = socialText(locale).media;
  return t.errors[code] ?? t.genericError;
};

/** The text for a post error code; unknown codes get the generic text. */
export const postMessage = (code: string, locale: "en" | "de") => {
  const t = socialText(locale).posts;
  return t.errors[code] ?? t.genericError;
};

/** The text for a validation issue of one account. */
export const issueMessage = (code: string, locale: "en" | "de") => {
  const t = socialText(locale).posts;
  return t.issues[code] ?? t.genericIssue;
};

/** Why a publication is held back or failed. */
export const publicationReason = (code: string, locale: "en" | "de") => {
  const t = socialText(locale);
  return t.publications.reasons[code] ?? t.posts.issues[code] ?? t.publications.genericReason;
};
