const tables: Record<Locale, Record<StatusCode, string>> = { en, de };

/** True for a code the status table has words for. */
export function isStatusCode(code: string): code is StatusCode {
  return Object.prototype.hasOwnProperty.call(en, code);
}

/**
 * The words of a status code in the locale. Null and undefined read as
 * "unknown"; an unknown code reads as before (underscores as spaces).
 */
export function statusLabel(locale: Locale, code: unknown): string {
  const raw = String(code ?? "unknown");
  return isStatusCode(raw)
    ? (tables[locale] ?? en)[raw]
    : raw.replaceAll("_", " ");
}
