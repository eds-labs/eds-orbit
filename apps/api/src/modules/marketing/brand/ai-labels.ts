// Marketing's side of the central AI image labelling (ADR 0028): which
// assets are AI images, the labelled derivative a raw generated image gets
// before it goes on a post, and the publish gate for an asset's bytes.
// Everything here is inert with `ORBIT_AI_IMAGE_LABELS` off.

/** The AI origins (an AI image needs the visible label). */
export type AiOrigin = Exclude<ImageOrigin, "original_upload">;
const AI_ORIGINS: readonly string[] = [
  "ai_generated",
  "ai_substantially_modified",
];
const aiOrigin = (value: unknown): AiOrigin | null =>
  AI_ORIGINS.includes(value as string) ? (value as AiOrigin) : null;

/** The publish gate's refusals, also preflight blocker codes. */
export const AI_LABEL_MISSING = "AI_LABEL_MISSING";
export const AI_LABEL_INVALID = "AI_LABEL_INVALID";
export const AI_LABEL_CODES: readonly string[] = [
  AI_LABEL_MISSING,
  AI_LABEL_INVALID,
];

/** A labelled image chosen as a component of a new composition (art, template visual). */
export const AI_LABELED_COMPONENT = "AI_LABELED_COMPONENT";

/** Whether an error is the publish gate's refusal (409 AI_LABEL_MISSING / AI_LABEL_INVALID). */
export const isAiLabelRefusal = (error: unknown): error is DomainError =>
  error instanceof DomainError && AI_LABEL_CODES.includes(error.code);

/** Creative layers the label never covers: logo, logo plate, copy and product. */
export const PROTECTED_LAYER_KINDS: ReadonlySet<LayerRecord["kind"]> = new Set([
  "logo",
  "logo_plate",
  "headline",
  "subline",
  "eyebrow",
  "cta",
  "product",
]);

/** The pixel boxes of a composition's protected layers. */
export const protectedBoxes = (layers: readonly LayerRecord[]): Box[] =>
  layers
    .filter((layer) => PROTECTED_LAYER_KINDS.has(layer.kind))
    .map((layer) => layer.box);

/** The `aiProvenance` field of an asset (a summary of the central record). */
export const aiProvenanceField = (
  origin: AiOrigin,
  labelState: "labeled" | "unlabeled_source",
  digitalSourceType: string | null,
) => ({ origin, labelState, digitalSourceType });

/** The `aiLabel` field of a labelled asset: the exact text, engine version and box. */
export const aiLabelField = (result: AiLabelResult) => ({
  text: AI_LABEL_TEXT,
  version: result.label.version,
  box: result.label.box,
});

/** Asset fields of a labelled image: its bytes and the label and provenance summaries. */
export const labeledAssetFields = (
  result: AiLabelResult,
  origin: AiOrigin,
) => ({
  base64: result.bytes.toString("base64"),
  sha256: result.sha256,
  bytes: result.bytes.length,
  aiProvenance: aiProvenanceField(origin, "labeled", result.digitalSourceType),
  aiLabel: aiLabelField(result),
});

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const HEX64 = /^[0-9a-f]{64}$/;

/** Generated by Orbit's image generation (including assets made before ADR 0028). */
const generatedRaw = (d: Record<string, any>) =>
  d.provider === "openai" ||
  d.source === "OpenAI Images API" ||
  d.sourceType === "AI_GENERATED";

/**
 * Whether an asset is an AI image, and with which origin, including assets
 * stored before ADR 0028 (never rewritten, §5): its `aiProvenance`; Orbit's
 * generated artwork (`provider` openai, the OpenAI source, `AI_GENERATED`);
 * a provenance record of its bytes; or a composition over AI art (creative
 * renditions by their rights components, banners by their background,
 * template renders by their visual, labelled derivatives by their source),
 * which counts as `ai_generated` (a composite). Null for anything else.
 */
export async function assetAiOrigin(
  tx: DbTx,
  scope: Pick<Scope, "workspaceId" | "projectId">,
  d: Record<string, any> | null | undefined,
  depth = 0,
): Promise<AiOrigin | null> {
  if (!d || typeof d !== "object") return null;
  const declared = aiOrigin(d.aiProvenance?.origin);
  if (declared) return declared;
  if (generatedRaw(d))
    return Number(d.referenceCount) > 0
      ? "ai_substantially_modified"
      : "ai_generated";
  const sha = String(d.sha256 ?? "").toLowerCase();
  if (HEX64.test(sha)) {
    const record = await imageProvenance(tx, scope, sha);
    if (record) return aiOrigin(record.origin);
  }
  if (depth >= 3) return null;
  const sources = new Set<string>();
  for (const component of Array.isArray(d.rightsSource?.components)
    ? d.rightsSource.components
    : [])
    if (component?.role === "art" && typeof component.assetId === "string")
      sources.add(component.assetId);
  for (const id of [
    d.visualAssetId,
    d.rightsSource?.backgroundAssetId,
    d.labeledFrom,
  ])
    if (typeof id === "string") sources.add(id);
  const ids = [...sources].filter((id) => UUID.test(id));
  if (!ids.length) return null;
  const rows = await tx.entity.findMany({
    where: {
      id: { in: ids },
      kind: "assets",
      workspaceId: scope.workspaceId,
      projectId: scope.projectId,
    },
  });
  for (const row of rows) {
    const origin = await assetAiOrigin(tx, scope, data(row), depth + 1);
    if (origin) return row.id === d.labeledFrom ? origin : "ai_generated";
  }
  return null;
}

/** Raw generated artwork (internal source material): it gets a labelled derivative before a post. */
const isRawGenerated = (d: Record<string, any>) =>
  !d.aiLabel &&
  !d.labeledFrom &&
  d.aiProvenance?.labelState !== "labeled" &&
  (generatedRaw(d) || d.aiProvenance?.labelState === "unlabeled_source");

// Fields a labelled derivative never copies from its source: lookups by
// generation, budget or run must keep finding only the source, and it is
// stored locally (no Drive copy of its own).
const NOT_COPIED = new Set([
  "generationId",
  "budgetReservationId",
  "assignmentRunId",
  "bannerBackground",
  "creativeArt",
  "bannerKey",
  "md5Checksum",
  "boundTo",
]);

type AssetRow = { id: string; version: number; data: unknown };

/**
 * The asset a post carries for this asset (ADR 0028 §3). Flag off, or not
 * raw generated artwork (an upload, a composed image, an already labelled
 * image): the row itself. Raw AI art: its labelled derivative, found by
 * `labeledFrom` and the source's bytes or created once, with the source's
 * metadata and approval, the labelled bytes (`labelFinalImage` with the
 * source's origin), `labeledFrom`, `aiProvenance` and `aiLabel`. The
 * derivative is bound to its source (`boundTo.labeledFrom`): kept out of the
 * library, pickers and art. Without inline bytes the image cannot be
 * labelled here: 409 AI_LABEL_MISSING. Labelling failures throw (fail closed).
 */
export async function ensureLabeledAsset<Row extends AssetRow>(
  tx: DbTx,
  scope: Scope,
  row: Row,
  createdBy: string,
): Promise<Row> {
  if (!aiImageLabelsEnabled()) return row;
  const d = data(row);
  if (!isRawGenerated(d)) return row;
  const origin = await assetAiOrigin(tx, scope, d);
  if (!origin) return row;
  // One derivative per source: concurrent runs wait here (until the first
  // commits) and then find its derivative. `scoped` also holds the project
  // lock; this one keeps the guarantee for any other transaction.
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${"orbit:ai-label-derivative:" + row.id}, 0))`;
  const sourceSha = String(d.sha256 ?? "").toLowerCase();
  const existing = await tx.entity.findFirst({
    where: {
      workspaceId: scope.workspaceId,
      projectId: scope.projectId,
      kind: "assets",
      AND: [
        { data: { path: ["labeledFrom"], equals: row.id } },
        { data: { path: ["labeledFromSha256"], equals: sourceSha } },
      ],
    },
    orderBy: { createdAt: "asc" },
  });
  if (existing) return existing as unknown as Row;
  if (typeof d.base64 !== "string")
    throw new DomainError(AI_LABEL_MISSING, 409);
  const { bytes } = assetBytes(d);
  const { result } = await labelFinalImage(tx, scope, {
    bytes,
    origin,
    subject: { module: "marketing", kind: "asset", id: row.id },
    createdBy: createdBy || scope.userId,
    parentSha256: sourceSha,
  });
  const copied = Object.fromEntries(
    Object.entries(d).filter(
      ([key]) => !NOT_COPIED.has(key) && !key.startsWith("drive"),
    ),
  );
  const derivative = await create(tx, scope, "assets", {
    ...copied,
    mime: result.mime,
    width: result.width,
    height: result.height,
    ...labeledAssetFields(result, origin),
    labeledFrom: row.id,
    labeledFromSha256: sourceSha,
    labeledFromVersion: row.version,
    boundTo: { labeledFrom: row.id },
    driveSyncStatus: "LOCAL_ONLY",
  });
  return derivative as unknown as Row;
}

/** Whether asset fields describe a labelled AI image. */
const labeledFields = (d: Record<string, any>) =>
  Boolean(d.aiLabel) || d.aiProvenance?.labelState === "labeled";

/**
 * What a new composition (Creative art, a template's visual) draws for an
 * asset (ADR 0028): a labelled image would keep its label inside the new
 * picture, which then gets a label of its own. A labelled derivative
 * composes from its unlabelled source (`labeledFrom`, while the source still
 * has the bytes it was labelled from), and so does a labelled image whose
 * record names an unlabelled asset of this project as its parent; any other
 * labelled image (a labelled upload, a labelled render or creative) is
 * refused with 409 AI_LABELED_COMPONENT. Unlabelled assets, and everything
 * with the flag off: the row itself. The caller checks the returned row's
 * type and approval as before.
 */
export async function composableAsset<Row extends { data: unknown }>(
  tx: DbTx,
  scope: Pick<Scope, "workspaceId" | "projectId">,
  row: Row,
): Promise<Row> {
  if (!aiImageLabelsEnabled()) return row;
  const d = data(row);
  const sha = String(d.sha256 ?? "").toLowerCase();
  const record = HEX64.test(sha) ? await imageProvenance(tx, scope, sha) : null;
  if (!labeledFields(d) && record?.labelState !== "labeled") return row;
  const where = {
    kind: "assets",
    workspaceId: scope.workspaceId,
    projectId: scope.projectId,
  };
  const usable = async (source: { data: unknown } | null) => {
    if (!source) return false;
    const s = data(source);
    if (labeledFields(s) || s.labeledFrom) return false;
    const own = HEX64.test(String(s.sha256 ?? "").toLowerCase())
      ? await imageProvenance(tx, scope, String(s.sha256).toLowerCase())
      : null;
    return own?.labelState !== "labeled";
  };
  if (typeof d.labeledFrom === "string" && UUID.test(d.labeledFrom)) {
    const source = await tx.entity.findFirst({
      where: { ...where, id: d.labeledFrom },
    });
    if (
      source &&
      String(data(source).sha256 ?? "").toLowerCase() ===
        String(d.labeledFromSha256 ?? "") &&
      (await usable(source))
    )
      return source as unknown as Row;
  }
  if (record?.parentSha256) {
    const source = await tx.entity.findFirst({
      where: { ...where, data: { path: ["sha256"], equals: record.parentSha256 } },
      orderBy: [{ createdAt: "asc" }, { id: "asc" }],
    });
    if (await usable(source)) return source as unknown as Row;
  }
  throw new DomainError(AI_LABELED_COMPONENT, 409);
}

/**
 * A labelled derivative still stands on its source: the source exists, is
 * approved and still has the bytes it was labelled from.
 */
export async function labeledSourceHolds(
  tx: DbTx,
  scope: Scope,
  d: Record<string, any>,
): Promise<boolean> {
  if (typeof d.labeledFrom !== "string" || !UUID.test(d.labeledFrom))
    return false;
  const source = await tx.entity.findFirst({
    where: {
      id: d.labeledFrom,
      kind: "assets",
      workspaceId: scope.workspaceId,
      projectId: scope.projectId,
    },
  });
  const s = data(source);
  return Boolean(
    source &&
    s.usageApproved === true &&
    s.assetStatus === "approved" &&
    String(s.sha256 ?? "").toLowerCase() === String(d.labeledFromSha256 ?? ""),
  );
}

/**
 * The post asset of a mission (its `assetIds` in turn), labelled when it is
 * raw AI art (`ensureLabeledAsset`). Unchanged with the flag off.
 */
export async function missionAssetId(
  tx: DbTx,
  scope: Scope,
  assetIds: readonly string[],
  completedRuns: number,
  createdBy: string,
): Promise<string> {
  const id = assetIds[completedRuns % assetIds.length]!;
  if (!aiImageLabelsEnabled() || !UUID.test(id)) return id;
  const row = await tx.entity.findFirst({
    where: {
      id,
      kind: "assets",
      workspaceId: scope.workspaceId,
      projectId: scope.projectId,
    },
  });
  return row ? (await ensureLabeledAsset(tx, scope, row, createdBy)).id : id;
}

/**
 * The publish gate for an asset's exact bytes in the caller's transaction:
 * null when they may leave Orbit (or the flag is off), else the refusal code
 * (`AI_LABEL_MISSING`, `AI_LABEL_INVALID`). The asset's AI origin (also of
 * assets made before ADR 0028) is the declared origin. `audit: false` is for
 * checks that only inform (preflight, also run for UI previews): no
 * `image.ai_label.blocked` record; outbound gates keep the default (true).
 */
export async function aiLabelBlocker(
  tx: DbTx,
  scope: Scope,
  asset: Record<string, any>,
  bytes: Buffer,
  context: string,
  options: { audit?: boolean } = {},
): Promise<string | null> {
  if (!aiImageLabelsEnabled()) return null;
  try {
    await assertAiLabelPublishable(tx, scope, {
      bytes,
      declaredOrigin: await assetAiOrigin(tx, scope, asset),
      context,
      audit: options.audit !== false,
    });
    return null;
  } catch (error) {
    if (isAiLabelRefusal(error)) return error.code;
    throw error;
  }
}

/**
 * The publish gate for an asset's exact bytes, outside any transaction: it
 * checks in its own project transaction, which commits the gate's audit
 * record, and then throws the refusal (409 AI_LABEL_MISSING /
 * AI_LABEL_INVALID). Flag off: no check, no transaction.
 */
export async function assertAssetPublishable(
  scope: Scope,
  asset: Record<string, any>,
  bytes: Buffer,
  context: string,
): Promise<void> {
  if (!aiImageLabelsEnabled()) return;
  const code = await scoped(scope.workspaceId, scope.projectId, (tx) =>
    aiLabelBlocker(tx, scope, asset, bytes, context),
  );
  if (code) throw new DomainError(code, 409);
}

/**
 * What an upload declares about itself (ADR 0028 §6): the ORIGINAL bytes'
 * reading (taken before normalization strips their XMP and C2PA), the AI
 * origin they name, and, when they carry Orbit's label, that label as it
 * verifies on the STORED bytes.
 */
export type UploadProvenance = {
  embedded: EmbeddedProvenance;
  origin: AiOrigin;
  /** The already drawn label, checked on the stored bytes; null when there is none. */
  label: AiLabelResult | null;
};

/**
 * Reads an upload's provenance from its original bytes and checks a label
 * they carry on the stored (normalized) bytes, so an already labelled image
 * is recorded as labelled and never gets a second label. A label named in
 * the XMP that does not show in the original's pixels counts as no label
 * (the image is then AI source material); one that shows in the original but
 * no longer in the stored bytes is refused (409 AI_LABEL_INVALID) rather
 * than covered by another. Null with the flag off. Bytes the reader cannot
 * open are refused like any invalid image.
 */
export async function readUploadProvenance(
  original: Buffer,
  stored: Buffer,
): Promise<UploadProvenance | null> {
  if (!aiImageLabelsEnabled()) return null;
  let embedded: EmbeddedProvenance;
  try {
    embedded = await readImageProvenance(original);
  } catch (error) {
    if (error instanceof CreativeError)
      throw new DomainError("ASSET_IMAGE_INVALID");
    throw error;
  }
  const origin = aiOrigin(embedded.xmp.origin) ?? "ai_generated";
  const box = embedded.xmp.label?.box;
  if (!box || !(await verifyAiLabel(original, box)).ok)
    return { embedded, origin, label: null };
  try {
    return {
      embedded,
      origin,
      label: await applyAiLabel(stored, { origin, knownLabel: box }),
    };
  } catch (error) {
    if (error instanceof CreativeError)
      throw new DomainError(
        error.code === "AI_LABEL_INPUT_INVALID"
          ? "ASSET_IMAGE_INVALID"
          : AI_LABEL_INVALID,
        error.code === "AI_LABEL_INPUT_INVALID" ? 400 : 409,
      );
    throw error;
  }
}

/** The IPTC term of a labelled upload: what the original declared, else Orbit's. */
const uploadSourceType = (upload: UploadProvenance, label: AiLabelResult) =>
  (AI_DIGITAL_SOURCE_TYPES as readonly string[]).includes(
    upload.embedded.xmp.digitalSourceType ?? "",
  )
    ? upload.embedded.xmp.digitalSourceType!
    : label.digitalSourceType;

/**
 * The asset fields of an upload whose original bytes declare AI: with a
 * verified label it is a labelled AI image (`aiProvenance.labelState`
 * "labeled" and `aiLabel`), used as it is; otherwise AI source material
 * (`unlabeled_source`), so compositions over it are labelled, a direct
 * attach gets a labelled derivative and preflight blocks the raw upload.
 * Nothing for any other upload (or with the flag off).
 */
export const uploadAssetFields = (upload: UploadProvenance | null) =>
  !upload?.embedded.declaresAi
    ? {}
    : upload.label
      ? {
          aiProvenance: aiProvenanceField(
            upload.origin,
            "labeled",
            uploadSourceType(upload, upload.label),
          ),
          aiLabel: aiLabelField(upload.label),
        }
      : {
          aiProvenance: aiProvenanceField(
            "ai_generated",
            "unlabeled_source",
            digitalSourceTypeFor("ai_generated"),
          ),
        };

/**
 * Records the stored (normalized) bytes of an uploaded asset (ADR 0028 §6):
 * an already labelled upload as `labeled` with its label box (verified on
 * the stored bytes); other AI-declaring originals as `unlabeled_source`;
 * both with the original's embedded provenance (a C2PA manifest store is
 * kept with the record). Anything else as `original_upload`, which never
 * gets a label. Null with the flag off.
 */
export async function recordUploadProvenance(
  tx: DbTx,
  scope: Scope,
  input: {
    upload: UploadProvenance | null;
    stored: Buffer;
    assetId: string;
    createdBy?: string;
  },
) {
  const { upload } = input;
  if (!upload || !aiImageLabelsEnabled()) return null;
  const subject = { module: "marketing", kind: "asset", id: input.assetId };
  const createdBy = input.createdBy || scope.userId;
  if (upload.embedded.declaresAi && upload.label)
    return recordImageProvenance(tx, scope, {
      sha256: upload.label.sha256,
      origin: upload.origin,
      labelState: "labeled",
      labelVersion: upload.label.label.version,
      labelBox: upload.label.label.box,
      labelContrast: upload.label.label.verifiedContrast,
      digitalSourceType: uploadSourceType(upload, upload.label),
      embedded: upload.embedded,
      subject,
      createdBy,
    });
  if (upload.embedded.declaresAi)
    return recordUnlabeledSource(tx, scope, {
      bytes: input.stored,
      origin: "ai_generated",
      subject,
      createdBy,
      embedded: upload.embedded,
    });
  // Stored bytes already recorded as AI (an earlier AI upload of the same
  // pixels) keep that record; the gate then decides by it.
  return (await recordOriginalUpload(tx, scope, { bytes: input.stored, subject, createdBy }))
    .provenance;
}
