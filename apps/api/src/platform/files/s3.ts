import { createHash, createHmac } from "node:crypto";

// A minimal S3-compatible object store client (WP4.6) for Cloudflare R2 and
// any S3 API: PUT, GET and DELETE of one object, signed with AWS Signature
// Version 4 over the payload's hash. No SDK: three calls do not justify one.
// Errors carry a code and the HTTP status only, never a key or a URL with
// credentials.

export type ObjectStoreConfig = {
  endpoint: string;
  bucket: string;
  region: string;
  accessKeyId: string;
  secretAccessKey: string;
};

export type ObjectStore = {
  put(key: string, body: Uint8Array): Promise<void>;
  /** The object's bytes, or null when it does not exist. */
  get(key: string): Promise<Uint8Array | null>;
  /** Deletes the object; a missing one counts as deleted. */
  delete(key: string): Promise<void>;
};

export class ObjectStoreError extends Error {
  constructor(
    readonly code: string,
    readonly status?: number,
  ) {
    super(code);
  }
}

type FetchLike = (url: string, init: RequestInit) => Promise<Response>;

const TIMEOUT_MS = 30_000;
// Object keys are generated by Orbit: path segments of these characters
// only, none starting with a dot (no "." or "..").
const KEY = /^[A-Za-z0-9_-][A-Za-z0-9._-]*(\/[A-Za-z0-9_-][A-Za-z0-9._-]*)*$/;

const sha256 = (data: string | Uint8Array) =>
  createHash("sha256").update(data).digest("hex");
const hmac = (key: string | Buffer, data: string) =>
  createHmac("sha256", key).update(data).digest();

/** RFC 3986 encoding, as Signature Version 4 requires. */
const encode = (value: string) =>
  encodeURIComponent(value).replace(
    /[!'()*]/g,
    (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`,
  );

/** `YYYYMMDDTHHMMSSZ` */
export const amzDate = (at: Date) =>
  at
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\.\d{3}/, "");

/**
 * Signs one request with AWS Signature Version 4 for the service `s3`.
 * Returns the headers to send: the given ones plus `x-amz-date`,
 * `x-amz-content-sha256` and `authorization`.
 */
export function signS3Request(input: {
  method: string;
  url: URL;
  headers: Record<string, string>;
  payloadHash: string;
  accessKeyId: string;
  secretAccessKey: string;
  region: string;
  now: Date;
}): Record<string, string> {
  const stamp = amzDate(input.now);
  const day = stamp.slice(0, 8);
  const headers: Record<string, string> = {};
  for (const [name, value] of Object.entries(input.headers))
    headers[name.toLowerCase()] = value;
  headers.host = input.url.host;
  headers["x-amz-date"] = stamp;
  headers["x-amz-content-sha256"] = input.payloadHash;
  const names = Object.keys(headers).sort();
  const canonicalHeaders = names
    .map((name) => `${name}:${headers[name]!.trim().replace(/\s+/g, " ")}\n`)
    .join("");
  const signedHeaders = names.join(";");
  const canonicalUri =
    input.url.pathname
      .split("/")
      .map((segment) => encode(decodeURIComponent(segment)))
      .join("/") || "/";
  const canonicalQuery = [...input.url.searchParams.entries()]
    .map(([k, v]) => [encode(k), encode(v)] as const)
    .sort(([a, x], [b, y]) => (a === b ? (x < y ? -1 : 1) : a < b ? -1 : 1))
    .map(([k, v]) => `${k}=${v}`)
    .join("&");
  const canonicalRequest = [
    input.method,
    canonicalUri,
    canonicalQuery,
    canonicalHeaders,
    signedHeaders,
    input.payloadHash,
  ].join("\n");
  const credentialScope = `${day}/${input.region}/s3/aws4_request`;
  const stringToSign = [
    "AWS4-HMAC-SHA256",
    stamp,
    credentialScope,
    sha256(canonicalRequest),
  ].join("\n");
  const key = hmac(
    hmac(hmac(hmac(`AWS4${input.secretAccessKey}`, day), input.region), "s3"),
    "aws4_request",
  );
  const signature = createHmac("sha256", key)
    .update(stringToSign)
    .digest("hex");
  return {
    ...headers,
    authorization: `AWS4-HMAC-SHA256 Credential=${input.accessKeyId}/${credentialScope}, SignedHeaders=${signedHeaders}, Signature=${signature}`,
  };
}

/** A path-style client for one bucket. */
export function s3Store(
  config: ObjectStoreConfig,
  options: { fetch?: FetchLike; now?: () => Date } = {},
): ObjectStore {
  const fetcher: FetchLike = options.fetch ?? ((url, init) => fetch(url, init));
  const base = new URL(config.endpoint);
  if (
    base.protocol !== "https:" &&
    !["localhost", "127.0.0.1"].includes(base.hostname)
  )
    throw new ObjectStoreError("OBJECT_STORE_ENDPOINT_INSECURE");
  const call = async (
    method: "PUT" | "GET" | "DELETE",
    key: string,
    body?: Uint8Array,
  ) => {
    if (!KEY.test(key)) throw new ObjectStoreError("OBJECT_KEY_INVALID");
    const url = new URL(base.toString());
    url.pathname = `${url.pathname.replace(/\/+$/, "")}/${config.bucket}/${key}`;
    const payload = body ?? new Uint8Array();
    const headers = signS3Request({
      method,
      url,
      headers: body
        ? {
            "content-type": "application/octet-stream",
            "content-length": String(body.byteLength),
          }
        : {},
      payloadHash: sha256(payload),
      accessKeyId: config.accessKeyId,
      secretAccessKey: config.secretAccessKey,
      region: config.region,
      now: (options.now ?? (() => new Date()))(),
    });
    // The host header is set by fetch itself.
    delete headers.host;
    delete headers["content-length"];
    try {
      return await fetcher(url.toString(), {
        method,
        headers,
        ...(body ? { body: Buffer.from(payload) } : {}),
        signal: AbortSignal.timeout(TIMEOUT_MS),
        redirect: "error",
      });
    } catch {
      throw new ObjectStoreError("OBJECT_STORE_UNREACHABLE");
    }
  };
  const fail = (response: Response): never => {
    throw new ObjectStoreError(
      response.status === 403 ? "OBJECT_STORE_AUTH" : "OBJECT_STORE_ERROR",
      response.status,
    );
  };
  return {
    async put(key, body) {
      const response = await call("PUT", key, body);
      if (!response.ok) fail(response);
    },
    async get(key) {
      const response = await call("GET", key);
      if (response.status === 404) return null;
      if (!response.ok) fail(response);
      return new Uint8Array(await response.arrayBuffer());
    },
    async delete(key) {
      const response = await call("DELETE", key);
      if (!response.ok && response.status !== 404) fail(response);
    },
  };
}
