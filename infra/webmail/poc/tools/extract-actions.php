<?php

// G5: builds the action inventory from the Roundcube source in the image.
// Usage: php extract-actions.php json|md
// Exits non-zero when the plugin policy names an action the source does not contain.

$root = '/var/www/html/';
$policy = require $root . 'plugins/orbit_bridge/actions.inc.php';
$inventory = [];

$add = static function (string $task, string $action, string $kind, string $source, ?string $aliasOf = null) use (&$inventory, $policy): void {
    $capability = $policy['*'][$action] ?? $policy[$task][$action] ?? 'deny';
    $inventory["{$task}/{$action}"] = array_filter([
        'capability' => $capability,
        'kind' => $kind,
        'source' => $source,
        'aliasOf' => $aliasOf,
    ]);
};

// One class per file: program/actions/<task>/<action>.php.
foreach (glob($root . 'program/actions/*/*.php') as $file) {
    $task = basename(dirname($file));
    $action = str_replace('_', '-', basename($file, '.php'));
    $add($task, $action, 'handler', substr($file, strlen($root)));

    if ($action === 'index' && preg_match('/\$aliases\s*=\s*\[(.*?)\];/s', file_get_contents($file), $block)) {
        preg_match_all("/'([^']+)'\s*=>\s*'([^']+)'/", $block[1], $pairs, PREG_SET_ORDER);
        foreach ($pairs as [, $alias, $target]) {
            $add($task, $alias, 'alias', substr($file, strlen($root)), $target);
        }
    }
}

// The addressbook task is rewritten to contacts in rcmail::action_handler().
foreach ($inventory as $key => $entry) {
    if (str_starts_with($key, 'contacts/')) {
        $add('addressbook', substr($key, strlen('contacts/')), 'task-alias', $entry['source']);
    }
}

// Dispatched by the core outside program/actions.
$add('*', 'keep-alive', 'core', 'program/include/rcmail.php:action_handler');
$add('*', 'save-pref', 'core', 'program/include/rcmail.php:action_handler');
$add('login', 'login', 'core', 'public_html/index.php');
$add('logout', 'index', 'core', 'public_html/index.php');
$add('dummy', 'index', 'core', 'program/include/rcmail.php:$main_tasks');
$add('mail', 'plugin.orbit_bridge.convert_reference', 'plugin', 'plugins/orbit_bridge/orbit_bridge.php');

ksort($inventory);

// Every policy entry must correspond to something the source can dispatch.
$stale = [];
foreach ($policy as $task => $actions) {
    foreach (array_keys($actions) as $action) {
        if (!isset($inventory["{$task}/{$action}"])) {
            $stale[] = "{$task}/{$action}";
        }
    }
}

if ($stale) {
    fwrite(STDERR, 'Stale policy entries: ' . implode(', ', $stale) . PHP_EOL);
    exit(1);
}

$counts = array_count_values(array_column($inventory, 'capability'));

if (($argv[1] ?? 'json') === 'json') {
    echo json_encode([
        'roundcube' => '1.7.6',
        'defaultCapability' => 'deny',
        'counts' => $counts,
        'actions' => $inventory,
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . PHP_EOL;
    exit(0);
}

echo "# Roundcube 1.7.6 action inventory\n\n";
echo "Generated by `poc/tools/extract-actions.php` from the source in the image. Unknown actions are denied.\n";
echo 'Totals: ' . implode(', ', array_map(static fn ($c, $n) => "{$c} {$n}", array_keys($counts), $counts)) . ".\n\n";
echo "| Task/action | Capability | Kind | Source |\n|---|---|---|---|\n";

foreach ($inventory as $key => $entry) {
    $alias = isset($entry['aliasOf']) ? " (alias of `{$entry['aliasOf']}`)" : '';
    echo "| `{$key}` | {$entry['capability']} | {$entry['kind']}{$alias} | `{$entry['source']}` |\n";
}
