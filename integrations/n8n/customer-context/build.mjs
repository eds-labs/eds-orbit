// Builds the importable n8n workflow definitions in workflows/ from src/.
// n8n Code nodes cannot import modules, so every node gets shared.js plus its
// module inlined (imports and `export` keywords removed) and a short entry
// snippet. The workflow JSON is generated, versioned and never edited in n8n.
//
//   node integrations/n8n/customer-context/build.mjs          write workflows/
//   node integrations/n8n/customer-context/build.mjs --check  fail on drift

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
// Bump with every change to src/ (semver): shown in every workflow and node.
export const VERSION = "1.1.0";

export const IDS = {
  gateway: "CcGatewayOrbit0001",
  desk: "CcAdapterUliquidDesk01",
  familyplan: "CcAdapterFamilyPlan001",
};
// Fixed so the production URL stays the same across re-imports.
const WEBHOOK_ID = "3f0c8d52-6a7e-4c1b-9d2f-0c1a5e7b9a41";
export const WEBHOOK_PATH = "orbit-cc/v1/customer-context/lookup";

function source(file) {
  return readFileSync(join(here, "src", file), "utf8")
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*"[^"]+";\n/m, "")
    .replace(/^export /gm, "");
}

function code(files, entry) {
  return [
    `// Generated by eds-orbit integrations/n8n/customer-context/build.mjs (v${VERSION}).`,
    "// Do not edit in n8n: change src/ in the repository and re-import.",
    "",
    ...files.map(source),
    "// --- entry ---",
    entry.trim(),
    "",
  ].join("\n");
}

const settings = (extra) => ({
  executionOrder: "v1",
  // Customer data must not stay in n8n: no execution data, no progress.
  saveDataSuccessExecution: "none",
  saveDataErrorExecution: "none",
  saveManualExecutions: false,
  saveExecutionProgress: false,
  executionTimeout: 10,
  ...extra,
});

const note = (text, position) => ({
  id: "note",
  name: "About",
  type: "n8n-nodes-base.stickyNote",
  typeVersion: 1,
  position,
  parameters: { content: text, width: 420, height: 220 },
});

const about = (what) =>
  `## ${what}\n\nGenerated from eds-orbit \`integrations/n8n/customer-context\` v${VERSION}. ` +
  "Do not edit here: change `src/`, run `build.mjs` and re-import.\n\n" +
  "Runbook: `integrations/n8n/customer-context/README.md`.";

function gateway() {
  const authenticate = code(
    ["shared.js", "gateway.js"],
    `
const crypto = require("crypto");
let raw = "";
try {
  raw = (await this.helpers.getBinaryDataBuffer(0, "data")).toString("utf8");
} catch {
  raw = "";
}
return [{ json: authenticate({
  raw,
  headers: $input.first().json.headers,
  now: Date.now(),
  integrations: parseIntegrations($env.CC_GATEWAY_INTEGRATIONS),
  crypto,
}) }];`,
  );
  const finalize = code(
    ["shared.js"],
    `
const request = $("Authenticate").first().json.request;
return [{ json: finalizeResponse(request, $input.first().json) }];`,
  );
  return {
    id: IDS.gateway,
    name: "Orbit Customer Context · Gateway v1",
    active: false,
    settings: settings({}),
    pinData: {},
    nodes: [
      note(about("Customer Context Gateway (workflow A)"), [-260, -320]),
      {
        id: "webhook",
        name: "Orbit lookup",
        type: "n8n-nodes-base.webhook",
        typeVersion: 2.2,
        position: [0, 0],
        webhookId: WEBHOOK_ID,
        parameters: {
          httpMethod: "POST",
          path: WEBHOOK_PATH,
          responseMode: "responseNode",
          options: { rawBody: true },
        },
      },
      {
        id: "authenticate",
        name: "Authenticate",
        type: "n8n-nodes-base.code",
        typeVersion: 2,
        position: [220, 0],
        parameters: { jsCode: authenticate },
      },
      {
        id: "authenticated",
        name: "Authenticated?",
        type: "n8n-nodes-base.if",
        typeVersion: 2.2,
        position: [440, 0],
        parameters: {
          conditions: {
            options: { caseSensitive: true, leftValue: "", typeValidation: "strict", version: 2 },
            conditions: [
              {
                id: "ok",
                leftValue: "={{ $json.ok }}",
                rightValue: true,
                operator: { type: "boolean", operation: "true", singleValue: true },
              },
            ],
            combinator: "and",
          },
          options: {},
        },
      },
      {
        id: "adapter",
        name: "Product adapter",
        type: "n8n-nodes-base.executeWorkflow",
        typeVersion: 1.2,
        position: [660, -100],
        // A failing adapter becomes a generic service_unavailable in Finalize.
        onError: "continueRegularOutput",
        parameters: {
          source: "database",
          workflowId: { __rl: true, value: "={{ $json.adapterWorkflowId }}", mode: "id" },
          options: { waitForSubWorkflow: true },
        },
      },
      {
        id: "finalize",
        name: "Finalize",
        type: "n8n-nodes-base.code",
        typeVersion: 2,
        position: [880, -100],
        parameters: { jsCode: finalize },
      },
      {
        id: "respond",
        name: "Respond",
        type: "n8n-nodes-base.respondToWebhook",
        typeVersion: 1.5,
        position: [1100, 0],
        parameters: {
          respondWith: "json",
          responseBody: "={{ JSON.stringify($json.body) }}",
          options: {
            responseCode: "={{ $json.status }}",
            responseHeaders: {
              entries: [
                { name: "cache-control", value: "no-store" },
                {
                  name: "content-type",
                  value: '={{ $json.status === 200 ? "application/json" : "application/problem+json" }}',
                },
              ],
            },
          },
        },
      },
    ],
    connections: {
      "Orbit lookup": { main: [[{ node: "Authenticate", type: "main", index: 0 }]] },
      Authenticate: { main: [[{ node: "Authenticated?", type: "main", index: 0 }]] },
      "Authenticated?": {
        main: [
          [{ node: "Product adapter", type: "main", index: 0 }],
          [{ node: "Respond", type: "main", index: 0 }],
        ],
      },
      "Product adapter": { main: [[{ node: "Finalize", type: "main", index: 0 }]] },
      Finalize: { main: [[{ node: "Respond", type: "main", index: 0 }]] },
    },
  };
}

function adapter({ id, name, title, module, run }) {
  const translate = code(
    ["shared.js", module],
    `
return [{ json: await ${run}({
  request: $input.first().json.request,
  env: $env,
  httpRequest: (options) => this.helpers.httpRequest(options),
  now: () => new Date(),
}) }];`,
  );
  return {
    id,
    name,
    active: false,
    // Only the gateway may run an adapter.
    settings: settings({ callerPolicy: "workflowsFromAList", callerIds: IDS.gateway }),
    pinData: {},
    nodes: [
      note(about(title), [-260, -320]),
      {
        id: "start",
        name: "From gateway",
        type: "n8n-nodes-base.executeWorkflowTrigger",
        typeVersion: 1.1,
        position: [0, 0],
        parameters: { inputSource: "passthrough" },
      },
      {
        id: "translate",
        name: "Lookup and translate",
        type: "n8n-nodes-base.code",
        typeVersion: 2,
        position: [220, 0],
        parameters: { jsCode: translate },
      },
    ],
    connections: {
      "From gateway": { main: [[{ node: "Lookup and translate", type: "main", index: 0 }]] },
    },
  };
}

export function workflows() {
  return {
    "gateway.json": gateway(),
    "adapter-uliquid-desk.json": adapter({
      id: IDS.desk,
      name: "Orbit Customer Context · Adapter uLiquid Desk v1",
      title: "uLiquid Desk adapter (workflow B)",
      module: "desk.js",
      run: "runDeskAdapter",
    }),
    "adapter-familyplan.json": adapter({
      id: IDS.familyplan,
      name: "Orbit Customer Context · Adapter FamilyPlan v1",
      title: "FamilyPlan adapter (workflow C)",
      module: "familyplan.js",
      run: "runFamilyPlanAdapter",
    }),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const drift = [];
  for (const [file, workflow] of Object.entries(workflows())) {
    const path = join(here, "workflows", file);
    const text = JSON.stringify(workflow, null, 2) + "\n";
    if (process.argv.includes("--check")) {
      let current = "";
      try {
        current = readFileSync(path, "utf8");
      } catch {}
      if (current !== text) drift.push(file);
    } else writeFileSync(path, text);
  }
  if (drift.length) {
    console.error(`Out of date, run build.mjs: ${drift.join(", ")}`);
    process.exit(1);
  }
  console.log(process.argv.includes("--check") ? "n8n workflows up to date" : "n8n workflows written");
}
